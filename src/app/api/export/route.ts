import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'

function formatReportData(data: Record<string, unknown>, indent = ''): string {
  const lines: string[] = []

  for (const [key, value] of Object.entries(data)) {
    const label = key
      .replace(/([A-Z])/g, ' $1')
      .replace(/^./, (s) => s.toUpperCase())
      .replace(/_/g, ' ')

    if (value === null || value === undefined) {
      lines.push(`${indent}${label}: N/A`)
    } else if (typeof value === 'string') {
      lines.push(`${indent}${label}: ${value}`)
    } else if (typeof value === 'number' || typeof value === 'boolean') {
      lines.push(`${indent}${label}: ${String(value)}`)
    } else if (Array.isArray(value)) {
      if (value.length === 0) {
        lines.push(`${indent}${label}: None`)
      } else {
        lines.push(`${indent}${label}:`)
        value.forEach((item, i) => {
          if (typeof item === 'object' && item !== null) {
            lines.push(`${indent}  ${i + 1}.`)
            lines.push(formatReportData(item as Record<string, unknown>, `${indent}     `))
          } else {
            lines.push(`${indent}  - ${String(item)}`)
          }
        })
      }
    } else if (typeof value === 'object') {
      lines.push(`${indent}${label}:`)
      lines.push(formatReportData(value as Record<string, unknown>, `${indent}  `))
    } else {
      lines.push(`${indent}${label}: ${String(value)}`)
    }
  }

  return lines.join('\n')
}

function generateTextReport(data: Record<string, unknown>, title: string): string {
  const timestamp = new Date().toISOString()

  const reportLines = [
    `${'═'.repeat(60)}`,
    `  TRUTHSHIELD ANALYSIS REPORT`,
    `${'═'.repeat(60)}`,
    ``,
    `  Title:      ${title}`,
    `  Generated:  ${new Date(timestamp).toLocaleString()}`,
    `  Platform:   TruthShield AI-Powered Digital Media Verification`,
    ``,
    `${'─'.repeat(60)}`,
    `  ANALYSIS RESULTS`,
    `${'─'.repeat(60)}`,
    ``,
    formatReportData(data, '  '),
    ``,
    `${'─'.repeat(60)}`,
    `  Report generated by TruthShield Platform`,
    `  © ${new Date().getFullYear()} TruthShield AI`,
    `${'═'.repeat(60)}`,
  ]

  return reportLines.join('\n')
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url)
    const reportId = searchParams.get('reportId')
    const format = searchParams.get('format') || 'json'

    if (!reportId) {
      return NextResponse.json(
        { error: 'reportId query parameter is required' },
        { status: 400 }
      )
    }

    const report = await db.analysisReport.findUnique({
      where: { id: reportId },
      include: {
        mediaUpload: {
          select: {
            fileName: true,
            fileType: true,
            mimeType: true,
            fileSize: true,
          },
        },
        factChecks: true,
      },
    })

    if (!report) {
      return NextResponse.json(
        { error: 'Analysis report not found' },
        { status: 404 }
      )
    }

    const reportData = {
      id: report.id,
      analysisType: report.analysisType,
      status: report.status,
      trustScore: report.trustScore,
      riskLevel: report.riskLevel,
      confidence: report.confidence,
      explanation: report.explanation,
      aiModel: report.aiModel,
      processingTime: report.processingTime,
      flags: report.flags ? JSON.parse(report.flags) : [],
      recommendations: report.recommendations ? JSON.parse(report.recommendations) : [],
      results: report.results ? JSON.parse(report.results) : null,
      mediaUpload: report.mediaUpload,
      factChecks: report.factChecks.map((fc) => ({
        source: fc.source,
        claim: fc.claim,
        verdict: fc.verdict,
        confidence: fc.confidence,
        url: fc.url,
        snippet: fc.snippet,
      })),
      createdAt: report.createdAt.toISOString(),
      updatedAt: report.updatedAt.toISOString(),
    }

    const filename = `truthshield-report-${report.analysisType}-${reportId.slice(-6)}`

    if (format === 'pdf') {
      const textContent = generateTextReport(
        reportData as unknown as Record<string, unknown>,
        `TruthShield ${report.analysisType.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())} Report`
      )
      return new NextResponse(textContent, {
        status: 200,
        headers: {
          'Content-Type': 'text/plain; charset=utf-8',
          'Content-Disposition': `attachment; filename="${filename}.txt"`,
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
          'Access-Control-Allow-Headers': 'Content-Type',
        },
      })
    }

    // Default: JSON format
    const jsonContent = JSON.stringify(reportData, null, 2)
    return new NextResponse(jsonContent, {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="${filename}.json"`,
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      },
    })
  } catch (error) {
    console.error('Export error:', error)
    return NextResponse.json(
      { error: 'Failed to export report' },
      { status: 500 }
    )
  }
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json()
    const { reportData, format, filename: customFilename } = body as {
      reportData: Record<string, unknown>
      format: 'json' | 'pdf'
      filename?: string
    }

    if (!reportData) {
      return NextResponse.json(
        { error: 'reportData is required' },
        { status: 400 }
      )
    }

    const filename = customFilename || `truthshield-report-${Date.now()}`

    if (format === 'pdf') {
      const analysisType = String(
        reportData.analysisType || reportData.type || 'analysis'
      )
      const textContent = generateTextReport(
        reportData,
        `TruthShield ${analysisType.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())} Report`
      )
      return new NextResponse(textContent, {
        status: 200,
        headers: {
          'Content-Type': 'text/plain; charset=utf-8',
          'Content-Disposition': `attachment; filename="${filename}.txt"`,
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
          'Access-Control-Allow-Headers': 'Content-Type',
        },
      })
    }

    // Default: JSON format
    const jsonContent = JSON.stringify(reportData, null, 2)
    return new NextResponse(jsonContent, {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="${filename}.json"`,
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      },
    })
  } catch (error) {
    console.error('Export error:', error)
    return NextResponse.json(
      { error: 'Failed to export report' },
      { status: 500 }
    )
  }
}

export async function OPTIONS() {
  return new NextResponse(null, {
    status: 204,
    headers: {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type',
    },
  })
}
